"""escape: pack the Overture address points (scripts/11_fetch_addresses.py) into the compact index the address lookup reads.
Usage: python3 scripts/12_address_index.py <addresses.json> [--region sf]
Writes dataset[_sf]/addresses_<area>.csv.gz (one row per street number, a table a person can open) and site/data[_sf]/addresses.js
(window.GT_ADDR). Nothing about the person using the page is collected: the lookup runs in their browser against this file."""
import sys, os, re, json, gzip, csv, base64, struct
from collections import defaultdict
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1]
SF = "--region" in sys.argv and sys.argv[sys.argv.index("--region") + 1] == "sf"
W, E, S, N = (-122.520, -122.360, 37.705, 37.825) if SF else (-122.215, -122.055, 37.805, 37.925)
DS = os.path.join(ROOT, "dataset_sf" if SF else "dataset"); SITE = os.path.join(ROOT, "site", "data_sf" if SF else "data")
AREA = "san_francisco" if SF else "lamorinda"
rows = json.load(open(SRC))
def title(s):
    s = re.sub(r"\s+", " ", s.strip()).title()
    s = re.sub(r"\b(\d+)(St|Nd|Rd|Th)\b", lambda m: m.group(1) + m.group(2).lower(), s)
    return s.replace("'S ", "'s ")
def city(c):
    c = c.strip().title()
    return c if c and not c.isdigit() and c not in ("Ca", "Ventura County") else ""
best = {}                                       # (street, city, number) -> first point; units at one door collapse to one row
for num, street, cty, pc, lon, lat in rows:
    m = re.match(r"\s*(\d+)", str(num))
    if not m or not street: continue
    n = int(m.group(1))
    if n <= 0 or n > 65535: continue
    k = (title(street), city(cty), n)
    if k not in best: best[k] = (lon, lat, pc)
by = defaultdict(list)
for (st, cty, n), (lon, lat, pc) in best.items(): by[(st, cty)].append((n, lon, lat))
keys = sorted(by, key=lambda k: (k[0], k[1]))
cities = sorted({k[1] for k in keys})
QX, QY = (E - W) / 65535, (N - S) / 65535
buf = bytearray(); streets = []
for st, cty in keys:
    pts = sorted(by[(st, cty)])
    streets.append([st, cities.index(cty), len(buf) // 6, len(pts)])
    for n, lon, lat in pts:
        buf += struct.pack("<HHH", n, round((lon - W) / QX), round((lat - S) / QY))
with gzip.open(os.path.join(DS, f"addresses_{AREA}.csv.gz"), "wt", newline="") as f:
    w = csv.writer(f); w.writerow(["number", "street", "city", "lon", "lat"])
    for st, cty in keys:
        for n, lon, lat in sorted(by[(st, cty)]): w.writerow([n, st, cty, lon, lat])
meta = dict(source="Overture Maps Foundation, theme addresses (overturemaps-us-west-2 on AWS open data), release " + os.environ.get("OVERTURE_RELEASE", "2026-11-18.0"),
            addresses=len(best), streets=len(keys), bbox=[W, S, E, N], q=[QX, QY])
js = "/* Generated by scripts/12_address_index.py from Overture Maps address points. Do not edit. */\nwindow.GT_ADDR=" + json.dumps(dict(meta=meta, cities=cities, streets=streets, pts=base64.b64encode(bytes(buf)).decode()), separators=(",", ":")) + ";\n"
open(os.path.join(SITE, "addresses.js"), "w").write(js)
print(AREA, "addresses", len(best), "streets", len(keys), "cities", cities, "js bytes", len(js))
