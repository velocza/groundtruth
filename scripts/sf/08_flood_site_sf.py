"""SF site data, part 8: the San Francisco flood model's street predictions for the Ask view.

Reads local_model_sf/report.json and local_model_sf/predictions_sf_streets_2026-11-18.csv (written by
model/train_sf_flood.py and model/predict_sf_flood.py) and writes site/data_sf/flood_model.js. Nothing is recomputed
here: the page shows the saved predictions for the November 2026 storm, with the held-out results from the report.

Usage: python3 scripts/sf/08_flood_site_sf.py
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
rep = json.load(open(os.path.join(ROOT, 'local_model_sf', 'report.json')))
rows = list(csv.DictReader(open(os.path.join(ROOT, 'local_model_sf', 'predictions_sf_streets_2026-11-18.csv'))))
rows.sort(key=lambda r: -float(r['score']))
gm, t = rep['geography_map'], rep['tests_tuned']
meta = dict(
    hazard=rep['hazard'], status=rep['status'], storm_morning=gm['storm_morning'], flood_day='2026-11-18',
    rain_72h_mm=gm['rain_72h_mm'], api_mm=gm['api_mm'], n_streets=len(rows), configs_tried=rep['configs_tried'],
    trees=rep['best_cfg']['n_trees'], depth=rep['best_cfg']['max_depth'], cv_auc=round(rep['best_cv']['auc'], 3),
    test_winter2023=round(t['test_winter2023']['auc'], 3), test_nov2026=round(t['test_nov2026_storm']['auc'], 3),
    test_nov2026_where=round(t['test_nov2026_storm']['where'], 3), map_auc=round(gm['map_auc_reported_vs_not'], 3),
    top_features=[f for f, _ in rep['feature_importance'][:3]],
    caveat='Distance to the nearest road is its second-largest input (about a quarter of the gain), partly because 311 reports are filed from streets. Scores are uncalibrated rankings, not probabilities.')
streets = {r['street']: [float(r['score']), k + 1] for k, r in enumerate(rows)}
out = os.path.join(ROOT, 'site', 'data_sf', 'flood_model.js')
open(out, 'w').write('/* Generated by scripts/sf/08_flood_site_sf.py from local_model_sf/ (San Francisco flood model). Do not edit. */\nwindow.GT_FLOOD='
                     + json.dumps(dict(meta=meta, streets=streets), separators=(',', ':')) + ';\n')
print('wrote', out, os.path.getsize(out), 'bytes;', len(streets), 'streets; top:', ', '.join(r['street'] for r in rows[:5]))
