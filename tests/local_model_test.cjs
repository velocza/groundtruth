const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const ctx={atob:s=>Buffer.from(s,'base64').toString('binary')}; ctx.window=ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'site/data/local-model.js'),'utf8'),ctx);
ctx.GTModel={cellsForStreet:k=>k===0?[0,1,2]:[]};
vm.runInContext(fs.readFileSync(path.join(root,'site/js/local-model.js'),'utf8'),ctx);
const ml=ctx.GTLocalModel,fixture=JSON.parse(fs.readFileSync(path.join(root,'local_model_landslide/parity.json')));
fixture.X.forEach((x,i)=>assert.ok(Math.abs(ml.predict(x)-fixture.scores[i])<1e-9,'Python/JS parity'));
fixture.cells.forEach((c,i)=>{const x=ml.cellFeatures(c,fixture.X[i][9],fixture.X[i][10]);assert.ok(Math.abs(ml.predict(x)-fixture.scores[i])<1e-9,'browser features match Python');});
assert.equal(ml.street(1,60,120),null);
assert.throws(()=>ml.street(0,NaN,120));
assert.equal(ml.cellFeatures(0,60,120).length,12);
assert.ok(Number.isFinite(ml.street(0,60,120).score));
assert.equal(ml.street(0,800,120).score,ml.street(0,400,120).score);
const report=ml.report;
assert.equal(report.hazard,'landslide');
assert.ok(!report.features.some(n=>/ndvi|SIM|insar|elev|road/i.test(n)));
assert.equal(report.data.slides,1398);
assert.equal(report.holdout_winter2023.tuned.events.length,11);
assert.equal(ml.explain(0,60,120).length,6);
console.log('PASS: 32 Python/JS parity cases on stored and browser-built features, feature exclusions, held-out report, bounds, missing streets and non-finite input.');
